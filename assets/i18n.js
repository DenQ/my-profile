export function detectLang() {
  const saved = localStorage.getItem('lang');
  if (saved === 'en' || saved === 'ru') return saved;
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('ru') ? 'ru' : 'en';
}

export function resolvePhrase(key, lang, vars = {}) {
  const entry = dict[key];
  if (!entry) return null;
  let text = entry[lang] || entry.en;
  Object.entries(vars).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value));
  });
  return text;
}

function applyLangChrome(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    const key = node.getAttribute('data-i18n-aria');
    const entry = dict[key];
    if (!entry) return;
    node.setAttribute('aria-label', entry[lang] || entry.en);
  });

  document.querySelectorAll('.lang__btn').forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', String(active));
  });

  localStorage.setItem('lang', lang);
}

export function applyLang(lang, vars = {}) {
  applyLangChrome(lang);

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const text = resolvePhrase(node.getAttribute('data-i18n'), lang, vars);
    if (text == null) return;
    node.textContent = text;
  });
}
